const test = require("node:test");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const buildInputsHash = require("./buildInputsHash.util");

const { recordPathFor } = require("./rustSources.util");
const { tempDir } = require("../../test/helpers");

const { cargoManifestsFor, watchFilesFor } = buildInputsHash;

const SOURCE = "#[no_mangle]\npub fn fib(n: u32) -> u32 { n }\n";

const MANIFEST = [
    "[package]",
    'name = "probe"',
    'version = "0.1.0"',
    "",
    "[lib]",
    'crate-type = ["cdylib"]',
    'path = "math.rs"',
    "",
    "[dependencies]",
    'wasm-bindgen = "0.2.95"',
    "",
].join("\n");

const lockWith = (version) =>
    [
        "# This file is automatically @generated by Cargo.",
        "version = 4",
        "",
        "[[package]]",
        'name = "wasm-bindgen"',
        `version = "${version}"`,
        "",
    ].join("\n");

// A throwaway crate on disk. The hash reads the manifest pair off the file
// system, so the fixtures are files rather than strings.
function crate({ manifest = MANIFEST, lock = lockWith("0.2.95") } = {}) {
    const dir = tempDir("rs-inputs-");
    fs.writeFileSync(path.join(dir, "math.rs"), SOURCE);
    fs.writeFileSync(path.join(dir, "Cargo.toml"), manifest);
    if (lock !== null) {
        fs.writeFileSync(path.join(dir, "Cargo.lock"), lock);
    }
    return dir;
}

const hashOf = (dir, source = SOURCE) =>
    buildInputsHash(source, path.join(dir, "math.rs"), dir);

const cleanup = (dirs) =>
    dirs.forEach((dir) => fs.rmSync(dir, { recursive: true, force: true }));

test("gives one digest to one set of inputs", () => {
    const dirs = [crate(), crate()];
    try {
        assert.equal(hashOf(dirs[0]), hashOf(dirs[1]));
    } finally {
        cleanup(dirs);
    }
});

test("changes the digest when the lock resolves another version", () => {
    const dirs = [crate(), crate({ lock: lockWith("0.2.128") })];
    try {
        assert.notEqual(hashOf(dirs[0]), hashOf(dirs[1]));
    } finally {
        cleanup(dirs);
    }
});

test("changes the digest when the manifest changes without the lock", () => {
    const dirs = [
        crate(),
        crate({
            manifest: `${MANIFEST}\n[profile.release]\nopt-level = "z"\n`,
        }),
    ];
    try {
        assert.notEqual(hashOf(dirs[0]), hashOf(dirs[1]));
    } finally {
        cleanup(dirs);
    }
});

test("changes the digest when the source changes", () => {
    const dir = crate();
    try {
        assert.notEqual(hashOf(dir), hashOf(dir, `${SOURCE}// edit\n`));
    } finally {
        cleanup([dir]);
    }
});

test("gives a lockless crate a stable digest of its own", () => {
    const dirs = [crate({ lock: null }), crate({ lock: null }), crate()];
    try {
        assert.equal(hashOf(dirs[0]), hashOf(dirs[1]));
        assert.notEqual(hashOf(dirs[0]), hashOf(dirs[2]));
    } finally {
        cleanup(dirs);
    }
});

// A crate whose entry sits one folder below the manifest that owns it.
function nestedCrate(lock) {
    const dir = crate({
        manifest: MANIFEST.replace(
            'path = "math.rs"',
            'path = "nested/math.rs"',
        ),
        lock,
    });
    fs.mkdirSync(path.join(dir, "nested"));
    fs.writeFileSync(path.join(dir, "nested", "math.rs"), SOURCE);
    return dir;
}

test("reads the manifest pair of the crate that owns a nested entry", () => {
    const dirs = [
        nestedCrate(lockWith("0.2.95")),
        nestedCrate(lockWith("0.2.128")),
    ];
    try {
        const digests = dirs.map((dir) =>
            buildInputsHash(SOURCE, path.join(dir, "nested", "math.rs"), dir),
        );
        assert.notEqual(digests[0], digests[1]);
    } finally {
        cleanup(dirs);
    }
});

test("throws when no manifest owns the entry", () => {
    const dir = tempDir("rs-inputs-bare-");
    try {
        fs.writeFileSync(path.join(dir, "math.rs"), SOURCE);
        assert.throws(() => hashOf(dir), {
            message: /Cannot Find "Cargo\.toml" to create wasm/,
        });
    } finally {
        cleanup([dir]);
    }
});

test("lists the manifests the digest reads, so a loader can declare them", () => {
    const dir = crate();
    try {
        assert.deepEqual(cargoManifestsFor(path.join(dir, "math.rs"), dir), [
            path.join(dir, "Cargo.toml"),
            path.join(dir, "Cargo.lock"),
        ]);
    } finally {
        cleanup([dir]);
    }
});

test("leaves out a lock that does not exist", () => {
    const dir = crate({ lock: null });
    try {
        assert.deepEqual(cargoManifestsFor(path.join(dir, "math.rs"), dir), [
            path.join(dir, "Cargo.toml"),
        ]);
    } finally {
        cleanup([dir]);
    }
});

// Writes the record that a build of `math.rs` leaves for its module files.
const recordModules = (dir, files) =>
    fs.writeFileSync(
        recordPathFor(path.join(dir, "math.rs")),
        JSON.stringify(files),
    );

const dropRecord = (dir) =>
    fs.rmSync(recordPathFor(path.join(dir, "math.rs")), { force: true });

test("changes the digest when a recorded module file changes", () => {
    const dir = crate();
    const util = path.join(dir, "util.rs");
    try {
        fs.writeFileSync(util, "pub fn v() -> u32 { 1 }\n");
        const unrecorded = hashOf(dir);
        recordModules(dir, [util]);
        const recorded = hashOf(dir);
        assert.notEqual(recorded, unrecorded);
        assert.equal(hashOf(dir), recorded);

        fs.writeFileSync(util, "pub fn v() -> u32 { 2 }\n");
        const edited = hashOf(dir);
        assert.notEqual(edited, recorded);

        fs.rmSync(util);
        assert.notEqual(hashOf(dir), edited);
        assert.notEqual(hashOf(dir), unrecorded);
    } finally {
        dropRecord(dir);
        cleanup([dir]);
    }
});

test("lists the recorded module files and the manifests to watch", () => {
    const dir = crate();
    const util = path.join(dir, "util.rs");
    try {
        recordModules(dir, [util]);
        assert.deepEqual(watchFilesFor(path.join(dir, "math.rs"), dir), [
            util,
            path.join(dir, "Cargo.toml"),
            path.join(dir, "Cargo.lock"),
        ]);
    } finally {
        dropRecord(dir);
        cleanup([dir]);
    }
});

// A workspace whose member `app` owns `math.rs` and depends on the sibling `shared`.
function workspace() {
    const dir = tempDir("rs-inputs-ws-");
    const files = {
        "Cargo.toml":
            '[workspace]\nmembers = ["app", "shared"]\n\n[workspace.dependencies]\nwasm-bindgen = "0.2.95"\n',
        "Cargo.lock": lockWith("0.2.95"),
        "app/Cargo.toml":
            '[package]\nname = "app"\nversion = "0.1.0"\n\n[lib]\npath = "math.rs"\n\n[dependencies]\nwasm-bindgen.workspace = true\nshared = { path = "../shared" }\n',
        "app/math.rs": SOURCE,
        "shared/Cargo.toml": '[package]\nname = "shared"\nversion = "0.1.0"\n',
    };
    fs.mkdirSync(path.join(dir, "app"));
    fs.mkdirSync(path.join(dir, "shared"));
    Object.entries(files).forEach(([file, content]) =>
        fs.writeFileSync(path.join(dir, file), content),
    );
    return dir;
}

const memberHash = (dir) =>
    buildInputsHash(SOURCE, path.join(dir, "app", "math.rs"), dir);

test("changes the digest when a workspace or path dependency file changes", () => {
    const dir = workspace();
    try {
        ["Cargo.toml", "Cargo.lock", path.join("shared", "Cargo.toml")].reduce(
            (previous, file) => {
                fs.appendFileSync(path.join(dir, file), "\n# edit\n");
                const next = memberHash(dir);
                assert.notEqual(next, previous, file);
                return next;
            },
            memberHash(dir),
        );
    } finally {
        cleanup([dir]);
    }
});

test("lists the workspace and path dependency manifests to watch", () => {
    const dir = workspace();
    try {
        assert.deepEqual(watchFilesFor(path.join(dir, "app", "math.rs"), dir), [
            path.join(dir, "app", "Cargo.toml"),
            path.join(dir, "Cargo.lock"),
            path.join(dir, "Cargo.toml"),
            path.join(dir, "shared", "Cargo.toml"),
        ]);
    } finally {
        cleanup([dir]);
    }
});
